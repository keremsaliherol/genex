-- Hesap Masası: ASP.NET Core Identity tabloları (Faz 5; tek yönetici, rol yok)
-- Kaynak: KimlikDbContext modelinden EF Core'un ürettiği DDL (Database.GenerateCreateScript, Oracle sağlayıcısı,
-- 19c uyumluluk modu). Tırnaksız büyük harf adlar ve dizin adları şemanın geri kalanındaki kurala çevrildi;
-- kolon tipleri ve uzunlukları modelle aynıdır. Migration kullanılmaz: model değişirse DDL yeniden üretilir.
-- Yönetici hesabını uygulama ilk açılışta oluşturur; parola Yonetici:Parola ayarından okunur, koda yazılmaz.
-- =====================================================================

CREATE TABLE ASPNET_USERS (
    ID                     VARCHAR2(900)  NOT NULL,
    USER_NAME              VARCHAR2(256),
    NORMALIZED_USER_NAME   VARCHAR2(256),
    EMAIL                  VARCHAR2(256),
    NORMALIZED_EMAIL       VARCHAR2(256),
    EMAIL_CONFIRMED        NUMBER(1)      NOT NULL,
    PASSWORD_HASH          VARCHAR2(4000),
    SECURITY_STAMP         VARCHAR2(4000),
    CONCURRENCY_STAMP      VARCHAR2(4000),
    PHONE_NUMBER           VARCHAR2(4000),
    PHONE_NUMBER_CONFIRMED NUMBER(1)      NOT NULL,
    TWO_FACTOR_ENABLED     NUMBER(1)      NOT NULL,
    LOCKOUT_END            TIMESTAMP(7) WITH TIME ZONE,
    LOCKOUT_ENABLED        NUMBER(1)      NOT NULL,
    ACCESS_FAILED_COUNT    NUMBER(10)     NOT NULL,
    CONSTRAINT PK_ASPNET_USERS PRIMARY KEY (ID),
    CONSTRAINT CK_ASPNET_USERS_BAYRAK CHECK (EMAIL_CONFIRMED IN (0, 1) AND PHONE_NUMBER_CONFIRMED IN (0, 1)
                                             AND TWO_FACTOR_ENABLED IN (0, 1) AND LOCKOUT_ENABLED IN (0, 1)),
    CONSTRAINT CK_ASPNET_USERS_DENEME CHECK (ACCESS_FAILED_COUNT >= 0)
);

-- Kullanıcı adı benzersiz (Oracle'da tamamen NULL anahtar dizine girmez; SQL Server'daki süzgeçli dizinle aynı anlam)
CREATE UNIQUE INDEX UQ_ASPNET_USERS_USER_NAME ON ASPNET_USERS (NORMALIZED_USER_NAME);
CREATE INDEX IDX_ASPNET_USERS_EMAIL ON ASPNET_USERS (NORMALIZED_EMAIL);

CREATE TABLE ASPNET_USER_CLAIMS (
    ID          NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    USER_ID     VARCHAR2(900)  NOT NULL,
    CLAIM_TYPE  VARCHAR2(4000),
    CLAIM_VALUE VARCHAR2(4000),
    CONSTRAINT PK_ASPNET_USER_CLAIMS PRIMARY KEY (ID),
    CONSTRAINT FK_ASPNET_USER_CLAIMS_USER FOREIGN KEY (USER_ID) REFERENCES ASPNET_USERS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_ASPNET_USER_CLAIMS_USER ON ASPNET_USER_CLAIMS (USER_ID);

CREATE TABLE ASPNET_USER_LOGINS (
    LOGIN_PROVIDER        VARCHAR2(900)  NOT NULL,
    PROVIDER_KEY          VARCHAR2(900)  NOT NULL,
    PROVIDER_DISPLAY_NAME VARCHAR2(4000),
    USER_ID               VARCHAR2(900)  NOT NULL,
    CONSTRAINT PK_ASPNET_USER_LOGINS PRIMARY KEY (LOGIN_PROVIDER, PROVIDER_KEY),
    CONSTRAINT FK_ASPNET_USER_LOGINS_USER FOREIGN KEY (USER_ID) REFERENCES ASPNET_USERS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_ASPNET_USER_LOGINS_USER ON ASPNET_USER_LOGINS (USER_ID);

-- Birincil anahtar USER_ID ile başladığı için yabancı anahtara ayrı dizin gerekmez
CREATE TABLE ASPNET_USER_TOKENS (
    USER_ID        VARCHAR2(900)  NOT NULL,
    LOGIN_PROVIDER VARCHAR2(900)  NOT NULL,
    NAME           VARCHAR2(900)  NOT NULL,
    VALUE          VARCHAR2(4000),
    CONSTRAINT PK_ASPNET_USER_TOKENS PRIMARY KEY (USER_ID, LOGIN_PROVIDER, NAME),
    CONSTRAINT FK_ASPNET_USER_TOKENS_USER FOREIGN KEY (USER_ID) REFERENCES ASPNET_USERS (ID) ON DELETE CASCADE
);

-- =====================================================================
-- Hesap Masası: şema
-- Oracle 19c ve üstü ile uyumludur (23ai'ye özel BOOLEAN, IF NOT EXISTS vb. kullanılmaz).
--
-- Temel kural: HESAP.BAKIYE hiçbir zaman doğrudan yazılmaz. Her para hareketi
-- ISLEM tablosuna bir kayıt olarak girer; TRG_ISLEM_BAKIYE_GUNCELLE bakiyeyi günceller.
-- Şartnamedeki şemaya eklenenler (arayüz planından):
--   * HISSE tablosu ve ISLEM.HISSE_KODU / ADET / BIRIM_FIYAT: portföy ekranı adet ve fiyat ister
--   * ISLEM.REFERANS_NO: transferin iki kaydını (giden + gelen) birbirine bağlar
--   * HESAP.EK_NO: hesap numarasındaki ek no (1001-<müşteri no>-<ek no>)
--   * CHECK kısıtları: negatif bakiye, pasif hesapta bakiye, eksik transfer/hisse bilgisi
-- Kimlik kolonları BY DEFAULT ON NULL: tohum veri prototiple aynı ID'lerle yüklenebilsin diye.
-- =====================================================================

CREATE TABLE MUSTERI (
    MUSTERI_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    MUSTERI_NO     VARCHAR2(20)  NOT NULL,
    AD_SOYAD       VARCHAR2(150) NOT NULL,
    EPOSTA         VARCHAR2(150),
    TELEFON        VARCHAR2(20),
    MUSTERI_TIPI   VARCHAR2(20)  DEFAULT 'BIREYSEL' NOT NULL,
    KAYIT_TARIHI   DATE          DEFAULT SYSDATE NOT NULL,
    AKTIF          NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_MUSTERI PRIMARY KEY (MUSTERI_ID),
    CONSTRAINT UQ_MUSTERI_NO UNIQUE (MUSTERI_NO),
    CONSTRAINT CK_MUSTERI_NO_BICIM CHECK (REGEXP_LIKE(MUSTERI_NO, '^[0-9]{8}$')),
    CONSTRAINT CK_MUSTERI_TIPI CHECK (MUSTERI_TIPI IN ('BIREYSEL', 'KURUMSAL')),
    CONSTRAINT CK_MUSTERI_AKTIF CHECK (AKTIF IN (0, 1))
);

CREATE TABLE HESAP (
    HESAP_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    MUSTERI_ID     NUMBER        NOT NULL,
    HESAP_NO       VARCHAR2(30)  NOT NULL,
    EK_NO          NUMBER(3)     NOT NULL,
    HESAP_TIPI     VARCHAR2(20)  DEFAULT 'VADESIZ' NOT NULL,
    BAKIYE         NUMBER(18,2)  DEFAULT 0 NOT NULL,
    ACILIS_TARIHI  DATE          DEFAULT SYSDATE NOT NULL,
    AKTIF          NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_HESAP PRIMARY KEY (HESAP_ID),
    CONSTRAINT FK_HESAP_MUSTERI FOREIGN KEY (MUSTERI_ID) REFERENCES MUSTERI (MUSTERI_ID),
    CONSTRAINT UQ_HESAP_NO UNIQUE (HESAP_NO),
    CONSTRAINT UQ_HESAP_MUSTERI_EK UNIQUE (MUSTERI_ID, EK_NO),
    CONSTRAINT CK_HESAP_TIPI CHECK (HESAP_TIPI IN ('VADESIZ', 'YATIRIM')),
    CONSTRAINT CK_HESAP_BAKIYE CHECK (BAKIYE >= 0),
    CONSTRAINT CK_HESAP_AKTIF CHECK (AKTIF IN (0, 1)),
    CONSTRAINT CK_HESAP_PASIF_BAKIYE CHECK (AKTIF = 1 OR BAKIYE = 0)
);

CREATE TABLE HISSE (
    HISSE_KODU         VARCHAR2(10)  NOT NULL,
    AD                 VARCHAR2(100) NOT NULL,
    TEMSILI_FIYAT      NUMBER(18,4)  NOT NULL,
    GUNCELLEME_TARIHI  DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_HISSE PRIMARY KEY (HISSE_KODU),
    CONSTRAINT CK_HISSE_FIYAT CHECK (TEMSILI_FIYAT > 0)
);

CREATE TABLE ISLEM (
    ISLEM_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    HESAP_ID        NUMBER        NOT NULL,
    ISLEM_TIPI      VARCHAR2(20)  NOT NULL,
    TUTAR           NUMBER(18,2)  NOT NULL,
    ISLEM_TARIHI    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ACIKLAMA        VARCHAR2(300),
    KARSI_HESAP_ID  NUMBER,
    REFERANS_NO     VARCHAR2(20),
    HISSE_KODU      VARCHAR2(10),
    ADET            NUMBER(12),
    BIRIM_FIYAT     NUMBER(18,4),
    CONSTRAINT PK_ISLEM PRIMARY KEY (ISLEM_ID),
    CONSTRAINT FK_ISLEM_HESAP FOREIGN KEY (HESAP_ID) REFERENCES HESAP (HESAP_ID),
    CONSTRAINT FK_ISLEM_KARSI_HESAP FOREIGN KEY (KARSI_HESAP_ID) REFERENCES HESAP (HESAP_ID),
    CONSTRAINT FK_ISLEM_HISSE FOREIGN KEY (HISSE_KODU) REFERENCES HISSE (HISSE_KODU),
    CONSTRAINT CK_ISLEM_TIPI CHECK (ISLEM_TIPI IN ('YATIRMA', 'CEKME', 'TRANSFER_GELEN', 'TRANSFER_GIDEN', 'ALIM', 'SATIM')),
    CONSTRAINT CK_ISLEM_TUTAR CHECK (TUTAR > 0),
    CONSTRAINT CK_ISLEM_KARSI_FARKLI CHECK (KARSI_HESAP_ID IS NULL OR KARSI_HESAP_ID <> HESAP_ID),
    -- CHECK kısıtı UNKNOWN sonucu kabul eder; bu yüzden NULL kontrolleri açıkça yazıldı.
    CONSTRAINT CK_ISLEM_TRANSFER CHECK (
        (ISLEM_TIPI IN ('TRANSFER_GELEN', 'TRANSFER_GIDEN') AND KARSI_HESAP_ID IS NOT NULL AND REFERANS_NO IS NOT NULL)
        OR (ISLEM_TIPI NOT IN ('TRANSFER_GELEN', 'TRANSFER_GIDEN') AND KARSI_HESAP_ID IS NULL)),
    CONSTRAINT CK_ISLEM_HISSE CHECK (
        (ISLEM_TIPI IN ('ALIM', 'SATIM') AND HISSE_KODU IS NOT NULL AND ADET IS NOT NULL AND BIRIM_FIYAT IS NOT NULL AND ADET > 0 AND BIRIM_FIYAT > 0)
        OR (ISLEM_TIPI NOT IN ('ALIM', 'SATIM') AND HISSE_KODU IS NULL AND ADET IS NULL AND BIRIM_FIYAT IS NULL))
);

-- İndeksler
CREATE INDEX IDX_HESAP_MUSTERI     ON HESAP (MUSTERI_ID);
-- Ekstre ve aylık özet: hesap + tarih aralığı. Şartnamedeki IDX_ISLEM_HESAP'ı da kapsar.
CREATE INDEX IDX_ISLEM_HESAP_TARIH ON ISLEM (HESAP_ID, ISLEM_TARIHI);
-- Genel bakış ve en aktif raporu: tüm hesaplarda tarih aralığı
CREATE INDEX IDX_ISLEM_TARIH       ON ISLEM (ISLEM_TARIHI);
CREATE INDEX IDX_ISLEM_REFERANS    ON ISLEM (REFERANS_NO);
-- Yabancı anahtar indeksleri: indekssiz FK, üst tabloda güncelleme/silmede tablo kilidine yol açar.
CREATE INDEX IDX_ISLEM_KARSI_HESAP ON ISLEM (KARSI_HESAP_ID);
CREATE INDEX IDX_ISLEM_HISSE       ON ISLEM (HISSE_KODU);

-- Transfer referans numarası: TRF + YYAAGG + 5 hane. Tohum veri 90000'in altında kalır.
CREATE SEQUENCE SEQ_REFERANS START WITH 90000 INCREMENT BY 1 CACHE 20;

-- Veri sözlüğü açıklamaları
COMMENT ON TABLE  MUSTERI IS 'Bireysel ve kurumsal müşteriler. Silme yok; AKTIF = 0 soft delete.';
COMMENT ON TABLE  HESAP   IS 'Müşteri hesapları. BAKIYE yalnız TRG_ISLEM_BAKIYE_GUNCELLE ile değişir.';
COMMENT ON TABLE  HISSE   IS 'Hisse tanımları ve temsili (gerçek piyasa verisi olmayan) fiyatlar.';
COMMENT ON TABLE  ISLEM   IS 'Tüm para hareketleri. Transfer iki kayıt olarak yazılır, REFERANS_NO ile bağlanır.';
COMMENT ON COLUMN HESAP.HESAP_NO     IS 'Şube (1001) + müşteri no + ek no, ör. 1001-40218375-01';
COMMENT ON COLUMN ISLEM.REFERANS_NO  IS 'Transfer çiftinin ortak referansı; diğer işlemlerde NULL.';
COMMENT ON COLUMN ISLEM.BIRIM_FIYAT  IS 'Hisse işleminde kullanılan temsili birim fiyat.';
